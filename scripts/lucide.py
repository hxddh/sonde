"""Writes app/src/ui/lucide.ts: the Lucide icons sonde draws, as typed data.

Usage: python3 -I scripts/lucide.py <lucide-static>/icon-nodes.json [version]

Only the icons in ICONS are written, so the bundle carries what sonde shows.
(After Native Shell's gallery, examples/gallery/scripts/lucide.py.)
"""

import json
import pathlib
import sys

ICONS = sorted(set("""
play square square-terminal list-clock database settings search folder folder-open file
chevron-right chevron-down chevron-left chevrons-up-down x check copy download upload
external-link ellipsis lock lock-open triangle-alert circle-alert info circle-check circle-x
refresh-cw git-compare-arrows repeat-2 app-window panel-left panel-right list-filter clock
timer arrow-up arrow-down layers boxes hard-drive cloud server key-round shield-check trash
plus pencil sparkles activity gauge chart-gantt sun moon languages bell zoom-in zoom-out link
share-2 package archive calendar-clock radio circle-dot plug flask-conical scale chart-pie
file-clock scroll-text undo-2 command keyboard monitor rotate-ccw ban
""".split()))

nodes = json.loads(pathlib.Path(sys.argv[1]).read_text())
version = sys.argv[2] if len(sys.argv) > 2 else "?"
NUM = {"cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "x1", "y1", "x2", "y2"}
out = [
    f"// Generated by scripts/lucide.py from lucide-static {version}: do not edit.",
    "// Lucide (https://lucide.dev), ISC License, Copyright (c) Lucide Contributors.",
    "",
    "/** One element of a Lucide icon, on its 24 × 24 grid. */",
    "export type LucideElement =",
    '  | { tag: "path"; d: string }',
    '  | { tag: "circle"; cx: number; cy: number; r: number }',
    '  | { tag: "ellipse"; cx: number; cy: number; rx: number; ry: number }',
    '  | { tag: "rect"; x: number; y: number; width: number; height: number; rx?: number }',
    '  | { tag: "line"; x1: number; y1: number; x2: number; y2: number }',
    '  | { tag: "polyline" | "polygon"; points: string };',
    "",
    "export const lucide = {",
]
for name in ICONS:
    els = []
    for tag, attrs in nodes[name]:
        e = {"tag": tag}
        for k, v in attrs.items():
            if k == "key" or k == "fill" or (tag == "rect" and k == "ry"):
                continue
            e[k] = float(v) if k in NUM else v
        els.append(e)
    out.append(f"  {json.dumps(name)}: {json.dumps(els)},")
out += ["} satisfies Record<string, LucideElement[]>;", "", "export type IconName = keyof typeof lucide;", ""]
pathlib.Path("app/src/ui/lucide.ts").write_text("\n".join(out))
print(len(ICONS), "icons")
