// `{name}` takes the argument of that name; one pass, so an argument's own
// text (a key named "{n}.json") is never read as a placeholder
function fill(template: string, args: Record<string, string>): string {
  return template.replace(/\{([A-Za-z0-9]+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(args, name) ? args[name] : whole,
  );
}

/**
 * A text (phrases said one after the other) beside its English: Chinese
 * when `zh` and every phrase has a template, else the English, whole.
 */
export function sayCoreText(text: CorePhrase[] | undefined, en: string, zh: boolean): string {
  if (!zh || !text || text.length === 0) return en;
  let out = "";
  for (const p of text) {
    const template = corePhrasesZh[p.key];
    if (template === undefined) return en;
    out += fill(template, p.args ?? {});
  }
  return out;
}
